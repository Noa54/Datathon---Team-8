use database bank;

CREATE OR REPLACE TABLE CLEAN.CANDIDATE_PAIRS AS

SELECT

A.CUSTOMER_ID AS TOTARA_ID,

B.CUSTOMER_ID AS HARBOURSIDE_ID,


A.FULL_NAME AS TOTARA_NAME,

B.FULL_NAME AS HARBOURSIDE_NAME,


A.DOB AS TOTARA_DOB,

B.DOB AS HARBOURSIDE_DOB,


A.TAX_ID AS TOTARA_TAX_ID,

B.TAX_ID AS HARBOURSIDE_TAX_ID,


A.PHONE AS TOTARA_PHONE,

B.PHONE AS HARBOURSIDE_PHONE,


A.ADDRESS AS TOTARA_ADDRESS,

B.ADDRESS AS HARBOURSIDE_ADDRESS,


A.EMAIL AS TOTARA_EMAIL,

B.EMAIL AS HARBOURSIDE_EMAIL


FROM CLEAN.TOTARA_CUSTOMERS A

JOIN CLEAN.HARBOURSIDE_CUSTOMERS B


ON

(
A.TAX_ID = B.TAX_ID
AND A.TAX_ID IS NOT NULL
)

OR

(
A.PHONE = B.PHONE
AND A.PHONE IS NOT NULL
)

OR

(
A.DOB = B.DOB
AND A.DOB IS NOT NULL
);


CREATE OR REPLACE TABLE CLEAN.CUSTOMER_MATCH_FEATURES AS

SELECT

TOTARA_ID,

HARBOURSIDE_ID,


-- Identifier features

CASE 
WHEN TOTARA_TAX_ID = HARBOURSIDE_TAX_ID
AND TOTARA_TAX_ID IS NOT NULL
THEN 1 ELSE 0 END 
AS TAX_ID_MATCH,


CASE 
WHEN TOTARA_PHONE = HARBOURSIDE_PHONE
AND TOTARA_PHONE IS NOT NULL
THEN 1 ELSE 0 END 
AS PHONE_MATCH,


CASE 
WHEN TOTARA_DOB = HARBOURSIDE_DOB
AND TOTARA_DOB IS NOT NULL
THEN 1 ELSE 0 END 
AS DOB_MATCH,


-- Name similarity

JAROWINKLER_SIMILARITY(
TOTARA_NAME,
HARBOURSIDE_NAME
)
AS NAME_SIMILARITY,


-- Address similarity

JAROWINKLER_SIMILARITY(
TOTARA_ADDRESS,
HARBOURSIDE_ADDRESS
)
AS ADDRESS_SIMILARITY

FROM CLEAN.CANDIDATE_PAIRS;

SELECT *
FROM CLEAN.CUSTOMER_MATCH_FEATURES
LIMIT 20;

CREATE OR REPLACE TABLE CLEAN.CUSTOMER_MATCH_SCORE AS

SELECT

*,

(
TAX_ID_MATCH * 60

+
PHONE_MATCH * 15

+
DOB_MATCH * 10

+
(NAME_SIMILARITY / 100) * 10

+
(ADDRESS_SIMILARITY / 100) * 5

)

AS MATCH_SCORE


FROM CLEAN.CUSTOMER_MATCH_FEATURES;


CREATE OR REPLACE TABLE CLEAN.CUSTOMER_MATCH_RESULTS AS

SELECT

*,

CASE

WHEN MATCH_SCORE >= 80
THEN 'MATCH'

ELSE 'NO_MATCH'

END AS MATCH_DECISION


FROM CLEAN.CUSTOMER_MATCH_SCORE;

select * from CLEAN.CUSTOMER_MATCH_RESULTS


SELECT 
MATCH_DECISION,
COUNT(*)

FROM CLEAN.CUSTOMER_MATCH_RESULTS

GROUP BY MATCH_DECISION;

SELECT *

FROM CLEAN.CUSTOMER_MATCH_RESULTS

WHERE MATCH_DECISION='MATCH'

ORDER BY MATCH_SCORE DESC;

SELECT 
MATCH_DECISION,
COUNT(*)
FROM CLEAN.CUSTOMER_MATCH_RESULTS
GROUP BY MATCH_DECISION;

