CREATE OR REPLACE SCHEMA CLEAN;

CREATE OR REPLACE TABLE CLEAN.TOTARA_CUSTOMERS AS

SELECT

CUST_NO AS CUSTOMER_ID,

LOWER(
REPLACE(FULL_NAME,',',' ')
) AS FULL_NAME,


DOB AS DOB,


REGEXP_REPLACE(
TO_VARCHAR(TAX_ID),
'[^0-9]',
''
) AS TAX_ID,


TO_VARCHAR(NZBN) AS NZBN,


LOWER(EMAIL_ADDR) AS EMAIL,


REGEXP_REPLACE(
COALESCE(CONTACT_PH_1,'') 
||
COALESCE(CONTACT_PH_2,''),
'[^0-9]',
''
) AS PHONE,


LOWER(
COALESCE(ADDR_1,'')
||' '
||COALESCE(ADDR_2,'')
||' '
||COALESCE(ADDR_3,'')
) AS ADDRESS


FROM PUBLIC.TOTARA_MUTUAL_CUSTOMERS;

CREATE OR REPLACE TABLE CLEAN.HARBOURSIDE_CUSTOMERS AS

SELECT

CUSTOMER_ID,

LOWER(
first_name
||' '
||COALESCE(middle_name,'')
||' '
||last_name
) AS FULL_NAME,


date_of_birth AS DOB,


REGEXP_REPLACE(
TO_VARCHAR(ird_number),
'[^0-9]',
''
) AS TAX_ID,


TO_VARCHAR(NZBN) AS NZBN,


LOWER(email) AS EMAIL,


REGEXP_REPLACE(
COALESCE(mobile_phone,'')
||
COALESCE(landline_phone,''),
'[^0-9]',
''
) AS PHONE,


LOWER(
street_address
||' '
||suburb
||' '
||city
||' '
||postcode
) AS ADDRESS


FROM PUBLIC.HARBOURSIDE_BANK_CUSTOMERS;



SELECT COUNT(*) AS MATCH_COUNT

FROM CLEAN.TOTARA_CUSTOMERS A

JOIN CLEAN.HARBOURSIDE_CUSTOMERS B

ON A.TAX_ID=B.TAX_ID;

SELECT COUNT(*)

FROM CLEAN.TOTARA_CUSTOMERS A

JOIN CLEAN.HARBOURSIDE_CUSTOMERS B

ON A.EMAIL=B.EMAIL;

SELECT COUNT(*)

FROM CLEAN.TOTARA_CUSTOMERS A

JOIN CLEAN.HARBOURSIDE_CUSTOMERS B

ON A.PHONE=B.PHONE;

SELECT COUNT(*)

FROM CLEAN.TOTARA_CUSTOMERS A

JOIN CLEAN.HARBOURSIDE_CUSTOMERS B

ON A.DOB=B.DOB;












CREATE OR REPLACE TABLE CLEAN.CANDIDATE_PAIRS AS

SELECT

A.CUSTOMER_ID AS TOTARA_ID,

B.CUSTOMER_ID AS HARBOURSIDE_ID,


A.FULL_NAME AS TOTARA_NAME,

B.FULL_NAME AS HARBOURSIDE_NAME,


A.DOB AS TOTARA_DOB,

B.DOB AS HARBOURSIDE_DOB,


A.TAX_ID AS TOTARA_TAX_ID,

B.TAX_ID AS HARBOURSIDE_TAX_ID,


A.PHONE AS TOTARA_PHONE,

B.PHONE AS HARBOURSIDE_PHONE


FROM CLEAN.TOTARA_CUSTOMERS A

JOIN CLEAN.HARBOURSIDE_CUSTOMERS B


ON

(
A.TAX_ID=B.TAX_ID
AND A.TAX_ID IS NOT NULL
)

OR

(
A.PHONE=B.PHONE
AND A.PHONE IS NOT NULL
)

OR

(
A.DOB=B.DOB
AND A.DOB IS NOT NULL
);