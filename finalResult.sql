use database bank;
DESC TABLE PUBLIC.BANK_MERGER_ANSWER_KEY;


CREATE OR REPLACE TABLE CLEAN.MATCH_EVALUATION AS

SELECT

P.TOTARA_ID,
P.HARBOURSIDE_ID,

P.MATCH_DECISION,


CASE

WHEN T.TRUEENTITYID = H.TRUEENTITYID

THEN 'MATCH'

ELSE 'NO_MATCH'

END AS TRUE_DECISION


FROM CLEAN.CUSTOMER_MATCH_RESULTS P


JOIN PUBLIC.BANK_MERGER_ANSWER_KEY T

ON T.BANK = 'Totara Mutual'

AND T.CUSTOMER_ID = LPAD(TO_VARCHAR(P.TOTARA_ID),8,'0')


JOIN PUBLIC.BANK_MERGER_ANSWER_KEY H

ON H.BANK = 'Harbourside Bank'

AND H.CUSTOMER_ID = P.HARBOURSIDE_ID;

SELECT COUNT(*)
FROM CLEAN.MATCH_EVALUATION;



SELECT

MATCH_DECISION,

TRUE_DECISION,

COUNT(*) AS COUNT

FROM CLEAN.MATCH_EVALUATION

GROUP BY 
MATCH_DECISION,
TRUE_DECISION

ORDER BY 
MATCH_DECISION,
TRUE_DECISION;





CREATE OR REPLACE TABLE CLEAN.MATCH_METRICS AS

SELECT

SUM(
CASE 
WHEN MATCH_DECISION='MATCH'
AND TRUE_DECISION='MATCH'
THEN 1 ELSE 0 END
) AS TP,


SUM(
CASE 
WHEN MATCH_DECISION='MATCH'
AND TRUE_DECISION='NO_MATCH'
THEN 1 ELSE 0 END
) AS FP,


SUM(
CASE 
WHEN MATCH_DECISION='NO_MATCH'
AND TRUE_DECISION='MATCH'
THEN 1 ELSE 0 END
) AS FN,


SUM(
CASE 
WHEN MATCH_DECISION='NO_MATCH'
AND TRUE_DECISION='NO_MATCH'
THEN 1 ELSE 0 END
) AS TN


FROM CLEAN.MATCH_EVALUATION;

SELECT *
FROM CLEAN.MATCH_METRICS;




